import assert from 'node:assert/strict'
import { existsSync } from 'node:fs'
import { mkdir } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { preview } from 'vite'
import { chromium } from 'playwright'
import { DEMO_CREDENTIALS } from '../src/features/authentication/services/mock_auth.js'

const root = fileURLToPath(new URL('../', import.meta.url))
const output = fileURLToPath(new URL('../test-results/community/', import.meta.url))
await mkdir(output, { recursive: true })
const server = await preview({ root, envDir: false, logLevel: 'error', preview: { host: '127.0.0.1', port: 5187, strictPort: true } })
const origin = 'http://127.0.0.1:5187'
const executablePath = process.env.LABX_BROWSER_PATH || ['C:/Program Files/Google/Chrome/Application/chrome.exe', 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'].find(existsSync)
let browser
let page

try {
  browser = await chromium.launch({ headless: true, ...(executablePath ? { executablePath } : {}) })
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce', timezoneId: 'Asia/Kolkata' })
  const errors = []
  const network = []
  const assetErrors = []
  await context.route('**/*', (route) => {
    const request = route.request()
    const url = new URL(request.url())
    if (url.origin !== origin && ['http:', 'https:'].includes(url.protocol)) {
      network.push(request.url())
      return route.abort()
    }
    if (['fetch', 'xhr'].includes(request.resourceType()) || /\/api(?:\/|$)/.test(url.pathname)) network.push(request.url())
    return route.continue()
  })
  page = await context.newPage()
  page.setDefaultTimeout(8000)
  await page.clock.setFixedTime(new Date('2026-10-14T04:30:00Z'))
  page.on('pageerror', (error) => errors.push(error.message))
  page.on('response', (response) => { if (response.status() >= 400) assetErrors.push(`${response.status()} ${response.url()}`) })
  const go = (path) => page.goto(`${origin}${path}`)
  const at = (path) => page.waitForURL(`${origin}${path}`)
  const heading = (name) => page.getByRole('heading', { name, exact: true, level: name === 'Sign in' ? 2 : 1 })
  const submit = () => page.locator('button[type="submit"]').click()
  const verifySignup = async () => {
    await at('/verify-email')
    const code = (await page.getByTestId('demo-signup-code').innerText()).trim()
    await page.getByLabel('Six-digit code', { exact: true }).fill(code)
    await page.getByRole('button', { name: 'Verify email', exact: true }).click()
  }
  const signOut = async () => { await page.getByRole('button', { name: 'Sign out', exact: true }).click(); await at('/login') }
  const closeDialog = async () => { await page.keyboard.press('Escape'); await page.locator('dialog[open]').waitFor({ state: 'hidden' }) }
  const checkLayout = async (name, widths = [320, 390, 768, 1440]) => {
    for (const width of widths) {
      await page.setViewportSize({ width, height: width < 600 ? 844 : 1000 })
      await page.evaluate(() => document.fonts.ready)
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true, `${name} fits ${width}px`)
      await page.screenshot({ path: `${output}${name}-${width}.png`, fullPage: true, animations: 'disabled' })
    }
  }
  const details = (title) => page.getByRole('button', { name: `View details: ${title}`, exact: true })
  const eventDialog = (title) => page.getByRole('dialog', { name: title, exact: true })

  for (const path of ['/events', '/achievements']) {
    await go(path)
    await at('/login')
    await heading('Sign in').waitFor()
  }
  await page.getByLabel('Email Address', { exact: true }).fill(DEMO_CREDENTIALS.email)
  await page.getByLabel('Password', { exact: true }).fill(DEMO_CREDENTIALS.password)
  await submit()
  await at('/dashboard')
  await heading('Dashboard').waitFor()
  assert.equal(await page.locator('.labx-brand-logo').evaluate((logo) => Boolean(logo.closest('a,button'))), false, 'Brand does not navigate')
  const sidebar = page.locator('.labx-sidebar-nav')
  for (const name of ['Dashboard', 'Roadmap', 'Leaderboard', 'Guilds', 'Social', 'Events', 'Achievements', 'Profile']) await sidebar.getByRole('link', { name, exact: true }).waitFor()
  assert.equal(await sidebar.getByRole('link', { name: 'Dashboard', exact: true }).getAttribute('aria-current'), 'page')
  const coin = page.getByRole('button', { name: '450 LabX Coins', exact: true })
  await coin.hover()
  assert.equal(await coin.getAttribute('aria-expanded'), 'true')
  await coin.focus()
  await page.keyboard.press('Escape')
  assert.equal(await coin.getAttribute('aria-expanded'), 'false')

  await sidebar.getByRole('link', { name: 'Roadmap', exact: true }).click()
  await at('/roadmap')
  await heading('Roadmap').waitFor()
  assert.equal(await page.getByRole('dialog').count(), 0, 'Project grid opens without an assessment gate')
  await sidebar.getByRole('link', { name: 'Achievements', exact: true }).click()
  await at('/achievements')
  await heading('Achievements').waitFor()
  assert.equal(await sidebar.getByRole('link', { name: 'Achievements', exact: true }).getAttribute('aria-current'), 'page')
  assert.equal(await page.locator('.achievements-summary > div').first().locator('strong').innerText(), '450')
  assert.equal(await page.locator('.achievement-card.is-earned').count(), 3)
  assert.equal(await page.locator('.achievement-card.is-locked').count(), 3)
  await checkLayout('achievements')
  await page.getByRole('button', { name: /^Earned/ }).click()
  assert.equal(await page.locator('.achievement-card').count(), 3)
  await page.getByRole('button', { name: 'View First Steps badge', exact: true }).click()
  const badge = page.getByRole('dialog', { name: 'First Steps', exact: true })
  await badge.waitFor()
  await badge.getByText('Earned date', { exact: true }).waitFor()
  await page.keyboard.press('Tab')
  assert.equal(await page.evaluate(() => Boolean(document.activeElement.closest('dialog'))), true)
  await checkLayout('badge-details', [320, 1440])
  await closeDialog()
  await page.getByRole('button', { name: /^Locked/ }).click()
  await page.getByRole('button', { name: 'View Quest Momentum badge', exact: true }).click()
  await page.getByRole('dialog', { name: 'Quest Momentum', exact: true }).getByText('Not earned yet', { exact: true }).waitFor()
  await closeDialog()
  await page.getByRole('button', { name: 'View Points History', exact: true }).click()
  const ledger = page.getByRole('dialog', { name: 'Points History', exact: true })
  await ledger.getByText('450 LabX Points', { exact: true }).waitFor()
  await ledger.getByText('Pending', { exact: true }).waitFor()
  await checkLayout('points-history', [320, 1440])
  await closeDialog()
  await page.getByRole('link', { name: 'View Leaderboard', exact: true }).click()
  await heading('Leaderboard').waitFor()
  await page.getByRole('table', { name: 'Founder rankings', exact: true }).waitFor()
  await page.getByRole('link', { name: 'Open profile for Demo Founder', exact: true }).click()
  await heading('Profile').waitFor()
  await page.getByText('founder@labx.demo', { exact: true }).waitFor()
  await page.getByRole('link', { name: 'Notifications', exact: true }).click()
  await heading('Notifications').waitFor()

  await page.setViewportSize({ width: 320, height: 844 })
  await page.getByRole('button', { name: 'More navigation', exact: true }).click()
  const menu = page.getByRole('dialog', { name: 'Your workspace', exact: true })
  await menu.waitFor()
  await page.screenshot({ path: `${output}navigation-320.png`, fullPage: true, animations: 'disabled' })
  await page.keyboard.press('Tab')
  assert.equal(await page.evaluate(() => Boolean(document.activeElement.closest('dialog'))), true)
  await closeDialog()
  await page.getByRole('button', { name: 'More navigation', exact: true }).click()
  await menu.getByRole('link', { name: 'Achievements', exact: true }).click()
  await heading('Achievements').waitFor()
  assert.equal(await menu.isVisible(), false)
  await page.getByRole('button', { name: 'More navigation', exact: true }).click()
  await menu.waitFor()
  await page.setViewportSize({ width: 1440, height: 1000 })
  await menu.waitFor({ state: 'hidden' })
  await sidebar.getByRole('link', { name: 'Events', exact: true }).click()
  await heading('Events & Opportunities').waitFor()
  await checkLayout('events')
  await page.getByLabel('Search events', { exact: true }).fill('no such event zzzz')
  await page.getByRole('heading', { name: 'No broadcasts found', exact: true }).waitFor()
  await page.getByRole('button', { name: 'Clear filters', exact: true }).click()
  await page.getByLabel('Category', { exact: true }).selectOption('Workshop')
  assert.equal(await page.locator('.events-card').count(), 1)
  await page.getByLabel('Format', { exact: true }).selectOption('In person')
  assert.equal(await page.locator('.events-card').count(), 0)
  await page.getByRole('button', { name: 'Clear filters', exact: true }).click()
  await page.getByRole('button', { name: 'Transmissions', exact: true }).click()
  await details('October Community Transmission').waitFor()
  assert.equal(await page.locator('.events-card').count(), 1)
  await page.getByRole('button', { name: 'All Broadcasts', exact: true }).click()
  await details('Customer Discovery Masterclass').click()
  await eventDialog('Customer Discovery Masterclass').getByRole('button', { name: 'Register', exact: true }).click()
  await eventDialog('Confirm registration').getByRole('button', { name: 'Cancel', exact: true }).click()
  await eventDialog('Customer Discovery Masterclass').getByRole('button', { name: 'Register', exact: true }).click()
  await eventDialog('Confirm registration').getByRole('button', { name: 'Confirm registration', exact: true }).click()
  const workshop = eventDialog('Customer Discovery Masterclass')
  await workshop.getByRole('status').filter({ hasText: 'Registration confirmed' }).waitFor()
  assert.equal(await workshop.getByRole('button', { name: 'Register', exact: true }).count(), 0)
  await workshop.getByRole('checkbox', { name: 'Save a reminder for this event' }).check()
  await checkLayout('event-details', [320, 1440])
  await closeDialog()
  await page.reload()
  await heading('Events & Opportunities').waitFor()
  await page.getByRole('button', { name: 'My Events (1)', exact: true }).click()
  assert.equal(await page.locator('.events-card').count(), 1)
  await details('Customer Discovery Masterclass').click()
  assert.equal(await workshop.getByRole('checkbox', { name: 'Save a reminder for this event' }).isChecked(), true)
  await workshop.getByRole('button', { name: 'Report listing', exact: true }).click()
  const report = eventDialog('Report listing')
  assert.equal(await report.getByRole('button', { name: 'Save report', exact: true }).isDisabled(), true)
  await report.getByLabel('Reason', { exact: true }).selectOption('Incorrect or outdated information')
  await report.getByLabel('Additional details (optional)', { exact: true }).fill('Sample report for this local preview.')
  await report.getByRole('button', { name: 'Save report', exact: true }).click()
  await workshop.getByRole('status').filter({ hasText: 'Report saved' }).waitFor()
  await closeDialog()
  await page.getByLabel('My Events period', { exact: true }).selectOption('past')
  await page.getByRole('heading', { name: 'No saved events match this view', exact: true }).waitFor()
  await page.getByRole('button', { name: 'Upcoming', exact: true }).click()
  for (const [title, status] of [['Mentor Exchange Circle', 'Not eligible'], ['Climate Sprint: Cohort Full', 'Fully booked'], ['Founder Showcase: Applications Closed', 'Registration closed']]) {
    await details(title).click()
    assert.equal(await eventDialog(title).getByRole('button', { name: status, exact: true }).isDisabled(), true)
    await closeDialog()
  }
  await details('Build for Impact Hackathon').click()
  await eventDialog('Build for Impact Hackathon').getByText(/Sponsored by LabX/).waitFor()
  await closeDialog()
  await page.getByRole('button', { name: 'Past', exact: true }).click()
  await details('Pitch Practice: October Edition').click()
  assert.equal(await eventDialog('Pitch Practice: October Edition').getByRole('button', { name: 'Event ended', exact: true }).isDisabled(), true)
  await closeDialog()
  await signOut()

  // New founders have their own empty rewards and event registrations.
  await go('/register')
  await page.getByLabel('Full Name', { exact: true }).fill('New Founder')
  await page.getByLabel('Email Address', { exact: true }).fill('new-founder@example.com')
  await page.getByLabel('Role', { exact: true }).selectOption('founder')
  await page.getByLabel('Password', { exact: true }).fill('FounderPass1!')
  await page.getByLabel('Confirm Password', { exact: true }).fill('FounderPass1!')
  await submit()
  await verifySignup()
  await at('/roadmap/new')
  await page.getByRole('link', { name: 'All projects', exact: true }).click()
  await at('/roadmap')
  await sidebar.getByRole('link', { name: 'Achievements', exact: true }).click()
  await heading('Achievements').waitFor()
  await page.getByRole('button', { name: '0 LabX Coins', exact: true }).waitFor()
  assert.equal(await page.locator('.achievement-card.is-earned').count(), 0)
  await page.getByRole('button', { name: /^Earned/ }).click()
  await page.getByRole('heading', { name: 'Your first badge is ahead', exact: true }).waitFor()
  await sidebar.getByRole('link', { name: 'Events', exact: true }).click()
  await page.getByRole('button', { name: 'My Events (0)', exact: true }).click()
  await page.getByRole('heading', { name: 'No saved events match this view', exact: true }).waitFor()
  await signOut()

  // Mentor navigation cannot reveal founder-only destinations.
  await go('/register')
  await page.getByLabel('Full Name', { exact: true }).fill('Taylor Mentor')
  await page.getByLabel('Email Address', { exact: true }).fill('taylor@example.com')
  await page.getByLabel('Role', { exact: true }).selectOption('mentor')
  await page.getByLabel('Password', { exact: true }).fill('MentorPass1!')
  await page.getByLabel('Confirm Password', { exact: true }).fill('MentorPass1!')
  await submit()
  await verifySignup()
  await at('/onboarding/mentor')
  await go('/dashboard')
  await heading('Dashboard').waitFor()
  for (const path of ['/roadmap', '/leaderboard', '/guild', '/social']) {
    assert.equal(await sidebar.locator(`a[href="${path}"]`).count(), 0)
    await go(path)
    await at('/dashboard')
  }
  await go('/achievements')
  await heading('Achievements').waitFor()
  assert.equal(await page.locator('.achievements-page a[href="/roadmap"], .achievements-page a[href="/leaderboard"]').count(), 0)
  await go('/events')
  await heading('Events & Opportunities').waitFor()
  await details('Mentor Exchange Circle').click()
  assert.equal(await eventDialog('Mentor Exchange Circle').getByRole('button', { name: 'Register', exact: true }).isEnabled(), true)
  await closeDialog()
  await page.setViewportSize({ width: 320, height: 844 })
  await page.getByRole('button', { name: 'More navigation', exact: true }).click()
  await menu.waitFor()
  assert.equal(await menu.getByRole('link', { name: 'Roadmap', exact: true }).count(), 0)
  await closeDialog()
  await signOut()
  await heading('Sign in').waitFor()
  assert.equal(await page.locator('.app-shell').count(), 0)
  assert.deepEqual(errors, [], 'No browser runtime errors')
  assert.deepEqual(assetErrors, [], 'All assets are available locally')
  assert.deepEqual(network, [], 'No external or backend requests')
  console.log('PASS: sidebar and mobile navigation, role guards, mock coin popup, badge details/filters/ledger, event discovery/registration/reminders/reports, account isolation, mobile layouts and no backend requests.')
} catch (error) {
  await page?.screenshot({ path: `${output}failure.png`, fullPage: true, animations: 'disabled' }).catch(() => {})
  throw error
} finally {
  await browser?.close()
  await new Promise((resolve, reject) => server.httpServer.close((error) => error ? reject(error) : resolve()))
}
