import assert from 'node:assert/strict'
import { existsSync } from 'node:fs'
import { mkdir } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { preview } from 'vite'
import { chromium } from 'playwright'
import { DEMO_CREDENTIALS } from '../src/features/authentication/services/mock_auth.js'

const root = fileURLToPath(new URL('../', import.meta.url))
const output = fileURLToPath(new URL('../test-results/projects/', import.meta.url))
await mkdir(output, { recursive: true })
const server = await preview({ root, envDir: false, logLevel: 'error', preview: { host: '127.0.0.1', port: 5188, strictPort: true } })
const origin = 'http://127.0.0.1:5188'
const executablePath = process.env.LABX_BROWSER_PATH || ['C:/Program Files/Google/Chrome/Application/chrome.exe', 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'].find(existsSync)
let browser
let page

try {
  browser = await chromium.launch({ headless: true, ...(executablePath ? { executablePath } : {}) })
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce', timezoneId: 'Asia/Kolkata' })
  const errors = []
  const network = []
  const assetErrors = []
  await context.route('**/*', (route) => {
    const request = route.request()
    const url = new URL(request.url())
    if (url.origin !== origin && ['http:', 'https:'].includes(url.protocol)) {
      network.push(request.url())
      return route.abort()
    }
    if (['fetch', 'xhr'].includes(request.resourceType()) || /\/api(?:\/|$)/.test(url.pathname)) network.push(request.url())
    return route.continue()
  })
  page = await context.newPage()
  page.setDefaultTimeout(8000)
  page.on('pageerror', (error) => errors.push(error.message))
  page.on('response', (response) => { if (response.status() >= 400) assetErrors.push(`${response.status()} ${response.url()}`) })
  const go = (path) => page.goto(`${origin}${path}`)
  const at = (path) => page.waitForURL(`${origin}${path}`)
  const heading = (name) => page.getByRole('heading', { name, exact: true, level: 1 })
  const row = (name) => page.getByRole('row', { name, exact: true })
  const option = (name) => page.getByRole('button', { name, exact: true })
  const next = () => option('Next Step').click()
  const back = () => option('Back').click()
  const list = async () => { await at('/roadmap'); await heading('Roadmap').waitFor() }
  const returnToProjects = async () => { await page.locator('.assessment-project-back').click(); await list() }
  const signOut = async () => { await option('Sign out').click(); await at('/login') }
  const closeDialog = async () => { await page.keyboard.press('Escape'); await page.locator('dialog[open]').waitFor({ state: 'hidden' }) }
  const countRows = async expected => {
    await page.waitForFunction(value => document.querySelectorAll('.project-row').length === value, expected)
    assert.equal(await page.locator('.project-row').count(), expected)
  }
  const checkLayout = async (name, widths = [320, 390, 768, 1440]) => {
    for (const width of widths) {
      await page.setViewportSize({ width, height: width < 600 ? 844 : 1000 })
      await page.evaluate(() => document.fonts.ready)
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true, `${name} fits ${width}px`)
      const table = page.locator('.projects-list table')
      if (await table.count()) {
        if (width === 1440) {
          const rowHeights = await table.locator('tbody .project-row').evaluateAll((rows) => rows.map((row) => row.getBoundingClientRect().height))
          assert.ok(rowHeights.length > 0 && rowHeights.every((height) => height > 0 && height <= 100), `${name} uses compact project rows at ${width}px: ${rowHeights.join(', ')}`)
        }
        if (width < 600) {
          const scroll = await page.locator('.projects-list').evaluate(el => ({ client:el.clientWidth, scroll:el.scrollWidth }))
          assert.ok(scroll.scroll <= scroll.client + 1, 'Compact project rows need no horizontal scrolling')
          const first = table.locator('tbody .project-row').first()
          assert.equal(await first.getByRole('button', {name:/^Edit /}).isVisible(),true,'Edit stays accessible on mobile')
          assert.equal(await first.getByRole('button', {name:/^Delete /}).isVisible(),true,'Delete stays accessible on mobile')
          assert.equal(await first.getByRole('link').isVisible(),true,'Project primary action stays visible')
        }
      }
      await page.screenshot({ path: `${output}${name}-${width}.png`, fullPage: true, animations: 'disabled' })
    }
  }
  const createProject = async (name) => {
    await page.getByRole('link', { name: 'New project', exact: true }).click()
    await at('/roadmap/new')
    await page.getByRole('textbox', { name: 'Project name', exact: true }).fill(name)
    await option('Start assessment').click()
    await page.waitForURL(/\/roadmap\/[^/]+\/assessment$/)
    await page.getByText(/Step 1 of 8/).waitFor()
    return new URL(page.url()).pathname.replace(/\/assessment$/, '')
  }
  const completeFromSolution = async (projectPath, domain) => {
    for (const answer of ['Web application', 'Exploring an idea', 'Not researched', 'Concept only', 'No target customers identified']) {
      await option(answer).click()
      await next()
    }
    await option('Problem clarity').click()
    await option('Review Answers').click()
    await page.getByRole('button', { name: 'Submit Assessment', exact: true }).click()
    await at(`${projectPath}/result`)
    await heading('Your assessment summary').waitFor()
    await page.getByText(domain, { exact: true }).waitFor()
  }
  const renameDialog = () => page.getByRole('dialog', { name: 'Edit project name', exact: true })
  const deleteDialog = () => page.getByRole('dialog', { name: 'Delete project?', exact: true })

  // An account can reach its project list without completing an assessment.
  await go('/login')
  await page.getByLabel('Email Address', { exact: true }).fill(DEMO_CREDENTIALS.email)
  await page.getByLabel('Password', { exact: true }).fill(DEMO_CREDENTIALS.password)
  await page.locator('button[type="submit"]').click()
  await at('/dashboard')
  await page.locator('.labx-sidebar-nav').getByRole('link', { name: 'Roadmap', exact: true }).click()
  await list()
  await countRows(0)
  assert.equal(await page.getByRole('dialog').count(), 0)
  await checkLayout('empty-projects')
  await page.getByRole('link', { name: 'New project', exact: true }).click()
  await page.getByRole('heading', { name: /Name your\s*project\./, level: 1 }).waitFor()
  assert.equal(await page.getByText(/Step 1 of 8/).count(), 0, 'Project name precedes assessment questions')
  await page.getByRole('textbox', { name: 'Project name', exact: true }).fill('   ')
  await option('Start assessment').click()
  await page.getByRole('alert').filter({ hasText: 'Enter a project name' }).waitFor()
  await at('/roadmap/new')
  await checkLayout('new-project')
  await page.getByRole('link', { name: 'All projects', exact: true }).click()
  await list()
  assert.equal(await page.locator('.project-row').count(), 0, 'Leaving the name form does not create an empty project')

  // Keep different answers and steps for two unfinished projects.
  const safetyPath = await createProject('Safe Streets')
  await option('Next Step').click(); await page.getByText('Please select an option before continuing.', { exact: true }).waitFor()
  await option('Women Safety & Social Impact').click()
  await next()
  await option('Individual consumers').click()
  await returnToProjects()
  await row('Safe Streets').getByText('Founder', { exact: true }).waitFor()
  const healthPath = await createProject('Health Bridge')
  assert.equal(await option('Women Safety & Social Impact').getAttribute('aria-pressed'), 'false', 'New project has an independent assessment')
  await option('Healthcare & MedTech').click()
  await next()
  await option('Healthcare providers').click()
  await next()
  await option('AI-powered software').click()
  await returnToProjects()
  await page.reload()
  await list()
  await countRows(2)
  await checkLayout('project-drafts')

  // Editing a draft changes the name while preserving its answers and step.
  await option('Edit Health Bridge').click()
  await renameDialog().waitFor()
  assert.equal(await renameDialog().getByLabel('Project name', { exact: true }).inputValue(), 'Health Bridge')
  await renameDialog().getByLabel('Project name', { exact: true }).fill('Unsaved health name')
  await page.keyboard.press('Shift+Tab')
  assert.equal(await page.evaluate(() => Boolean(document.activeElement.closest('dialog'))), true, 'Edit dialog contains keyboard focus')
  await closeDialog()
  assert.equal(await option('Edit Health Bridge').evaluate((element) => element === document.activeElement), true, 'Escape returns focus to the edit button')
  assert.equal(await row('Unsaved health name').count(), 0, 'Canceling an edit leaves the name unchanged')
  await option('Edit Health Bridge').click()
  await renameDialog().getByLabel('Project name', { exact: true }).fill('   ')
  await renameDialog().getByRole('button', { name: 'Save name', exact: true }).click()
  await renameDialog().getByRole('alert').filter({ hasText: 'Enter a project name' }).waitFor()
  await row('Health Bridge').waitFor()
  await renameDialog().getByLabel('Project name', { exact: true }).fill('Health Bridge Launch')
  await checkLayout('edit-project')
  await renameDialog().getByRole('button', { name: 'Save name', exact: true }).click()
  await renameDialog().waitFor({ state: 'hidden' })
  await page.getByRole('link', { name: 'Continue assessment: Health Bridge Launch', exact: true }).click()
  await at(`${healthPath}/assessment`)
  await page.getByText(/Step 3 of 8/).waitFor()
  assert.equal(await option('AI-powered software').getAttribute('aria-pressed'), 'true')
  await back()
  assert.equal(await option('Healthcare providers').getAttribute('aria-pressed'), 'true')
  await back()
  assert.equal(await option('Healthcare & MedTech').getAttribute('aria-pressed'), 'true')
  await returnToProjects()

  await page.getByRole('link', { name: 'Continue assessment: Safe Streets', exact: true }).click()
  await at(`${safetyPath}/assessment`)
  await page.getByText(/Step 2 of 8/).waitFor()
  assert.equal(await option('Individual consumers').getAttribute('aria-pressed'), 'true')
  await back()
  assert.equal(await option('Women Safety & Social Impact').getAttribute('aria-pressed'), 'true')
  await next()
  await next()
  await completeFromSolution(safetyPath, 'Women Safety & Social Impact')
  await option('Enter My Roadmap').click()
  await at(safetyPath)
  await heading('Safe Streets').waitFor()
  await option('Problem statement, Level 1, Mission 1, active').waitFor()
  assert.equal(await option('User context, Level 1, Mission 2, locked').isDisabled(), true, 'Assessment placement does not skip mission evidence')
  await page.getByRole('link', { name: 'All roadmaps', exact: true }).click()
  await list()
  await page.getByRole('link', { name: 'Continue assessment: Health Bridge Launch', exact: true }).click()
  await page.getByText(/Step 1 of 8/).waitFor()
  assert.equal(await option('Healthcare & MedTech').getAttribute('aria-pressed'), 'true')
  await next()
  await next()
  // The previously selected solution remains selected when resuming the project.
  await next()
  for (const answer of ['Exploring an idea', 'Not researched', 'Concept only', 'No target customers identified']) {
    await option(answer).click()
    await next()
  }
  await option('Problem clarity').click()
  await option('Review Answers').click()
    await page.getByRole('button', { name: 'Submit Assessment', exact: true }).click()
  await at(`${healthPath}/result`)
  await page.getByText('Healthcare & MedTech', { exact: true }).waitFor()
  await go('/roadmap')
  await list()

  // Completed assessments remain locked when a project is renamed.
  await option('Edit Safe Streets').click()
  await renameDialog().getByLabel('Project name', { exact: true }).fill('Safe Streets 2026')
  await renameDialog().getByRole('button', { name: 'Save name', exact: true }).click()
  await renameDialog().waitFor({ state: 'hidden' })
  assert.equal(await row('Safe Streets 2026').getByRole('link', { name: 'Open roadmap: Safe Streets 2026', exact: true }).count(), 1)
  assert.equal(await row('Safe Streets 2026').getByRole('link', { name: /assessment/i }).count(), 0)
  await go(`${safetyPath}/assessment`)
  await at(`${safetyPath}/result`)
  await page.getByText('Women Safety & Social Impact', { exact: true }).waitFor()
  await page.getByText('Safe Streets 2026', { exact: true }).waitFor()
  await option('Enter My Roadmap').click()
  await heading('Safe Streets 2026').waitFor()
  await option('Problem statement, Level 1, Mission 1, active').waitFor()
  await checkLayout('named-roadmap')
  await page.getByRole('link', { name: 'All roadmaps', exact: true }).click()
  await list()
  await checkLayout('completed-projects')

  // A cancellation preserves the project; confirmation removes only that project.
  await option('Delete Safe Streets 2026').click()
  await deleteDialog().waitFor()
  assert.match(await deleteDialog().innerText(), /Safe Streets 2026/)
  await checkLayout('delete-project')
  await page.keyboard.press('Tab')
  assert.equal(await page.evaluate(() => Boolean(document.activeElement.closest('dialog'))), true, 'Delete dialog contains keyboard focus')
  await deleteDialog().getByRole('button', { name: 'Cancel', exact: true }).click()
  await deleteDialog().waitFor({ state: 'hidden' })
  await row('Safe Streets 2026').waitFor()
  await option('Delete Safe Streets 2026').click()
  await closeDialog()
  assert.equal(await option('Delete Safe Streets 2026').evaluate((element) => element === document.activeElement), true, 'Escape returns focus to the delete button')
  await option('Delete Safe Streets 2026').click()
  await deleteDialog().getByRole('button', { name: 'Delete project', exact: true }).click()
  await deleteDialog().waitFor({ state: 'hidden' })
  assert.equal(await row('Safe Streets 2026').count(), 0)
  await page.reload()
  await list()
  await row('Health Bridge Launch').waitFor()
  await countRows(1)
  await go(safetyPath)
  await heading('Project not found').waitFor()
  await page.getByRole('link', { name: 'All projects', exact: true }).click()
  await list()

  // Search, filters and sorting apply to the whole collection, ten projects per page.
  const extraProjects = new Map()
  for (let index = 3; index <= 12; index++) {
    const name = `Research Project ${index}`
    extraProjects.set(name, await createProject(name))
    await returnToProjects()
  }
  await countRows(10)
  const pagination = page.getByRole('navigation', { name: 'Projects pagination' })
  assert.equal(await pagination.count(), 1)
  await pagination.getByRole('button', { name: 'Page 2', exact: true }).click()
  await countRows(1)
  assert.equal(await pagination.getByRole('button', { name: 'Page 2', exact: true }).getAttribute('aria-current'), 'page')
  await page.reload()
  await heading('Roadmap').waitFor()
  assert.equal(await page.locator('.project-row').count(), 1, 'Current page survives refresh')
  await page.getByRole('searchbox', { name: 'Search projects', exact: true }).fill('Research Project 12')
  await row('Research Project 12').waitFor()
  assert.equal(await page.locator('.project-row').count(), 1, 'Search finds projects across every page')
  assert.equal(await pagination.getByRole('button', { name: 'Page 1', exact: true }).getAttribute('aria-current'), 'page')
  await page.getByLabel('Status', { exact: true }).selectOption('ready')
  await page.getByRole('heading', { name: 'No projects match your search' }).waitFor()
  await option('Clear search and filters').click()
  await page.getByLabel('Domain', { exact: true }).selectOption('Healthcare & MedTech')
  await row('Health Bridge Launch').waitFor()
  await countRows(1)
  await option('Clear filters').click()
  await page.getByLabel('Status', { exact: true }).selectOption('pending')
  await page.waitForFunction(() => document.querySelectorAll('.project-row').length === 10)
  await countRows(10)
  await page.getByLabel('Sort by', { exact: true }).selectOption('name-asc')
  await page.locator('.project-row').first().getByRole('heading', { name: 'Research Project 3', exact: true }).waitFor()
  assert.equal(await page.locator('.project-row').first().getByRole('heading', { level: 2 }).innerText(), 'Research Project 3')
  await page.getByLabel('Sort by', { exact: true }).selectOption('name-desc')
  await page.locator('.project-row').first().getByRole('heading', { name: 'Research Project 12', exact: true }).waitFor()
  assert.equal(await page.locator('.project-row').first().getByRole('heading', { level: 2 }).innerText(), 'Research Project 12')
  await page.reload()
  await heading('Roadmap').waitFor()
  assert.equal(await page.getByLabel('Status', { exact: true }).inputValue(), 'pending')
  assert.equal(await page.getByLabel('Sort by', { exact: true }).inputValue(), 'name-desc')
  await option('Clear filters').click()
  await page.getByLabel('Sort by', { exact: true }).selectOption('updated')
  await checkLayout('paginated-projects')
  await pagination.getByRole('button', { name: 'Next page', exact: true }).click()
  await countRows(1)
  const finalPageName = await page.locator('.project-row').last().getByRole('heading', { level: 2 }).innerText()
  await option(`Delete ${finalPageName}`).click()
  await deleteDialog().getByRole('button', { name: 'Delete project', exact: true }).click()
  await deleteDialog().waitFor({ state: 'hidden' })
  assert.equal(await page.locator('.project-row').count(), 10, 'Deleting the last record on page two returns to page one')
  assert.equal(await pagination.getByRole('button', { name: 'Page 2', exact: true }).count(), 0)
  assert.equal(await pagination.getByRole('button', { name: 'Page 1', exact: true }).getAttribute('aria-current'), 'page')
  const remainingName = await page.locator('.project-row').first().getByRole('heading', { level: 2 }).innerText()
  const remainingPath = extraProjects.get(remainingName) || healthPath
  await page.reload()
  await list()
  await countRows(10)

  // Missing routes and another user's project IDs never expose project data.
  for (const suffix of ['', '/assessment', '/result']) {
    await go(`/roadmap/does-not-exist${suffix}`)
    await heading('Project not found').waitFor()
    assert.equal(await page.locator('.assessment-wizard').count(), 0)
    assert.equal(await option('Open current mission').count(), 0)
  }
  await signOut()
  await go('/register')
  await page.getByLabel('Full Name', { exact: true }).fill('Independent Founder')
  await page.getByLabel('Email Address', { exact: true }).fill('independent@example.com')
  await page.getByLabel('Role', { exact: true }).selectOption('founder')
  await page.getByLabel('Password', { exact: true }).fill('FounderPass1!')
  await page.getByLabel('Confirm Password', { exact: true }).fill('FounderPass1!')
  await page.locator('button[type="submit"]').click()
  await at('/verify-email')
  const code = (await page.getByTestId('demo-signup-code').innerText()).trim()
  await page.getByLabel('Digit 1 of 6', { exact: true }).fill(code)
  await page.getByRole('button', { name: 'Verify email', exact: true }).click()
  await at('/roadmap/new')
  await page.getByRole('link', { name: 'All projects', exact: true }).click()
  await list()
  await countRows(0)
  for (const suffix of ['', '/assessment', '/result']) {
    await go(`${remainingPath}${suffix}`)
    await heading('Project not found').waitFor()
    assert.equal(await page.getByText(remainingName, { exact: true }).count(), 0)
  }
  await go('/assessment')
  await at('/roadmap/new')
  await page.getByRole('link', { name: 'All projects', exact: true }).click()
  await list()
  await createProject('Independent Garden')
  await returnToProjects()
  await row('Independent Garden').getByText('Independent Founder', { exact: true }).waitFor()
  await go('/assessment/result')
  await list()
  await signOut()
  await page.getByLabel('Email Address', { exact: true }).fill(DEMO_CREDENTIALS.email)
  await page.getByLabel('Password', { exact: true }).fill(DEMO_CREDENTIALS.password)
  await page.locator('button[type="submit"]').click()
  await at('/dashboard')
  await page.locator('.labx-sidebar-nav').getByRole('link', { name: 'Roadmap', exact: true }).click()
  await list()
  await countRows(10)
  assert.equal(await row('Independent Garden').count(), 0)
  await row(remainingName).waitFor()

  assert.deepEqual(errors, [], 'No browser runtime errors')
  assert.deepEqual(assetErrors, [], 'All assets are available locally')
  assert.deepEqual(network, [], 'No external or backend requests')
  console.log('PASS: independent assessments, edits, deletion, search and combined filters, sorting, ten-project numbered pagination, refresh persistence, last-page deletion, account isolation and layouts at 320/390/768/1440px.')
} catch (error) {
  await page?.screenshot({ path: `${output}failure.png`, fullPage: true, animations: 'disabled' }).catch(() => {})
  throw error
} finally {
  await browser?.close()
  await new Promise((resolve, reject) => server.httpServer.close((error) => error ? reject(error) : resolve()))
}
