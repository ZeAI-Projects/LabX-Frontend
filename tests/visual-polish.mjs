import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { createServer } from 'vite';
import { chromium } from 'playwright';
import { DEMO_CREDENTIALS } from '../src/features/authentication/services/mock_auth.js';
const root=fileURLToPath(new URL('../',import.meta.url));
const output=new URL('../test-results/visual-polish/',import.meta.url);
await mkdir(output,{recursive:true});
const executablePath=['C:/Program Files/Google/Chrome/Application/chrome.exe','C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'].find(existsSync);
const server=await createServer({root,envDir:false,logLevel:'error',server:{host:'127.0.0.1',port:5199,strictPort:true}});
await server.listen();
const browser=await chromium.launch({headless:true,...(executablePath?{executablePath}:{})});
const context=await browser.newContext({viewport:{width:1440,height:960},reducedMotion:'reduce'});
const page=await context.newPage();
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const go=path=>page.goto('http://127.0.0.1:5199'+path);
const shot=name=>page.screenshot({path:fileURLToPath(new URL(name+'.png',output)),animations:'disabled'});
const fit=async name=>assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),true,name+' fits viewport');
try {
  await go('/forgot-password');
  await page.getByLabel('Email Address',{exact:true}).fill(DEMO_CREDENTIALS.email);
  await page.locator('button[type=submit]').click();await page.waitForURL('**/reset-password');
  await page.getByRole('heading',{name:'Reset your password',exact:true}).waitFor();
  assert.equal(await page.locator('.verification-digit').count(),6);
  assert.equal(await page.locator('.auth-mode-tabs:visible').count(),0);
  await shot('reset-desktop');
  await page.setViewportSize({width:320,height:844});await fit('Reset code');await shot('reset-mobile');
  await go('/login');
  await page.getByLabel('Email Address',{exact:true}).fill(DEMO_CREDENTIALS.email);
  await page.getByLabel('Password',{exact:true}).fill(DEMO_CREDENTIALS.password);
  await page.locator('button[type=submit]').click();await page.waitForURL('**/dashboard');
  const project=await page.evaluate(async()=>{
    const {projectStore}=await import('/src/features/projects/services/project_store.js');
    const complete=projectStore.createProject('Visual checkpoint');
    projectStore.completeProject(complete.id,{q1:2,q2:1,q3:1,q4:1,q5:1,q6:1,q7:1,q8:1});
    for(let i=1;i<=12;i++)projectStore.createProject('Project '+i);
    return complete.id;
  });
  await go('/roadmap');await page.locator('.project-row').first().waitFor();
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'Filters & sort',exact:true}).click();
  assert.equal(await page.getByLabel('Status',{exact:true}).isVisible(),true);
  await page.getByLabel('Status',{exact:true}).selectOption('ready');
  await page.getByRole('heading',{name:'Visual checkpoint',exact:true}).waitFor();
  await page.getByRole('button',{name:/Filters & sort/}).click();
  assert.equal(await page.getByLabel('Status',{exact:true}).isVisible(),false);
  await page.getByRole('button',{name:'Clear filters',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('.project-row').length===10);
  await fit('Mobile projects');
  const launcherBeforeScroll=await page.locator('.sharp-dock-trigger').boundingBox();
  assert.ok(Math.abs(launcherBeforeScroll.x+launcherBeforeScroll.width-390+14)<1,'Zenith stays in the mobile right corner');
  await page.evaluate(()=>scrollTo(0,600));
  await page.waitForFunction(()=>scrollY>0);
  const launcherAfterScroll=await page.locator('.sharp-dock-trigger').boundingBox();
  assert.ok(Math.abs(launcherAfterScroll.x-launcherBeforeScroll.x)<1&&Math.abs(launcherAfterScroll.y-launcherBeforeScroll.y)<1,'Zenith stays fixed while projects scroll');
  await page.evaluate(()=>scrollTo(0,0));
  await shot('projects-mobile');
  await page.getByRole('button',{name:'Page 2',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('.project-row').length===3);
  for(const route of ['/dashboard','/events','/leaderboard','/achievements','/profile','/companion']) {
    await go(route);await page.locator('main').waitFor();
    for(const width of [320,390,1440]){await page.setViewportSize({width,height:width<600?844:960});await fit(route+' '+width)}
    await shot(route.slice(1)+'-desktop');
  }
  assert.equal(await page.locator('.sharp-page .sharp-welcome__avatar').isVisible(),false,'Companion does not repeat the large welcome robot');
  await go('/events');await page.setViewportSize({width:390,height:844});
  assert.equal(await page.getByLabel('Category',{exact:true}).isVisible(),false);
  await page.getByRole('button',{name:/More filters/}).click();
  assert.equal(await page.getByLabel('Category',{exact:true}).isVisible(),true);
  await page.getByRole('button',{name:/More filters/}).click();await shot('events-mobile');
  await page.setViewportSize({width:1440,height:960});
  await go('/roadmap/'+project);
  await page.getByRole('region',{name:'Current stage navigation',exact:true}).waitFor();
  await page.getByRole('button',{name:'Locate current checkpoint',exact:true}).click();
  const contextBox=await page.locator('.rm-sticky-checkpoint').boundingBox();assert.ok(contextBox.y>=0&&contextBox.y<=20,'Stage context follows the page scroll');
  await page.getByRole('button',{name:'Problem statement, Level 1, Mission 1, active',exact:true}).click();
  const dialog=page.getByRole('dialog',{name:'Problem statement',exact:true});await dialog.waitFor();
  await dialog.getByLabel('Your work',{exact:true}).fill('We interviewed five target users, documented the repeated problems and their existing workarounds, and selected one clear problem to validate with a small measurable prototype. Our next experiment will test that assumption with the same users.');
  await dialog.getByLabel('Evidence link',{exact:true}).fill('https://example.test/research');
  await dialog.getByRole('button',{name:'Submit for evaluation',exact:true}).click();
  await dialog.getByRole('heading',{name:'Mission accepted',exact:true}).waitFor();
  assert.equal(await page.locator('.progress-celebration').count(),0,'Reward waits while a mission dialog is open');
  await dialog.getByRole('button',{name:'Close mission',exact:true}).click();
  await page.locator('.progress-celebration').waitFor();
  assert.equal(await page.locator('.progress-celebration').evaluate(el=>el.getAnimations({subtree:true}).length),0,'Celebration respects reduced motion');
  await shot('mission-completed');
  await page.getByRole('button',{name:'Dismiss celebration',exact:true}).click();
  assert.equal(await page.locator('html').getAttribute('data-labx-progress'),null);
  await page.reload();await page.locator('.rm-page').waitFor();
  assert.equal(await page.locator('.progress-celebration').count(),0,'Reload never invents a new completion');
  assert.deepEqual(errors,[]);
  console.log('PASS: six-box reset layouts, mobile filters and pagination, fixed right launcher, desktop/mobile page fit, persistent roadmap context, and real approval celebration after dialog close.');
} finally {await context.close();await browser.close();await server.close();}
